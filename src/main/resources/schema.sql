CREATE TABLE IF NOT EXISTS categoria (
  id BIGINT PRIMARY KEY, nome VARCHAR(50) NOT NULL UNIQUE, ativa BOOLEAN DEFAULT TRUE NOT NULL
);
CREATE TABLE IF NOT EXISTS usuario (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo VARCHAR(15) NOT NULL CHECK (tipo IN ('CLIENTE','PROFISSIONAL')),
  nome VARCHAR(100) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE, telefone VARCHAR(25) NOT NULL,
  senha_hash VARCHAR(220) NOT NULL, versao_sessao INT DEFAULT 0 NOT NULL,
  apresentacao VARCHAR(1000), cidade VARCHAR(100), bairros VARCHAR(400), recebedor VARCHAR(90)
);
CREATE TABLE IF NOT EXISTS atuacao (
  profissional_id BIGINT REFERENCES usuario, categoria_id BIGINT REFERENCES categoria,
  PRIMARY KEY (profissional_id, categoria_id)
);
CREATE TABLE IF NOT EXISTS acesso (
  email VARCHAR(254) PRIMARY KEY, falhas INT DEFAULT 0 NOT NULL,
  primeira_falha TIMESTAMP WITH TIME ZONE, bloqueio_ate TIMESTAMP WITH TIME ZONE
);
CREATE TABLE IF NOT EXISTS recuperacao (
  usuario_id BIGINT PRIMARY KEY REFERENCES usuario, codigo_hash VARCHAR(64) NOT NULL UNIQUE,
  validade TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE IF NOT EXISTS solicitacao (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id BIGINT NOT NULL REFERENCES usuario, categoria_id BIGINT NOT NULL REFERENCES categoria,
  titulo VARCHAR(100) NOT NULL, descricao VARCHAR(2000) NOT NULL, cidade VARCHAR(100) NOT NULL,
  bairro VARCHAR(100) NOT NULL, endereco VARCHAR(300) NOT NULL, preferencias VARCHAR(1000),
  frequencia VARCHAR(20), data_preferida TIMESTAMP WITH TIME ZONE,
  orcamento_min DECIMAL(12,2), orcamento_max DECIMAL(12,2), chave VARCHAR(80) NOT NULL,
  estado VARCHAR(30) NOT NULL CHECK (estado IN ('ABERTA','CONTRATADO','AGENDADO','EM_ANDAMENTO','AGUARDANDO_CONFIRMACAO','CONCLUIDO','CANCELADO')),
  criada_em TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
  atualizada_em TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
  inicio_real TIMESTAMP WITH TIME ZONE, concluida_em TIMESTAMP WITH TIME ZONE,
  UNIQUE(cliente_id,chave)
);
CREATE TABLE IF NOT EXISTS proposta (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  servico_id BIGINT NOT NULL REFERENCES solicitacao, profissional_id BIGINT NOT NULL REFERENCES usuario,
  valor DECIMAL(12,2) NOT NULL CHECK (valor>0), escopo VARCHAR(2000) NOT NULL,
  duracao_horas DECIMAL(8,2) NOT NULL CHECK (duracao_horas>0),
  estado VARCHAR(25) NOT NULL CHECK (estado IN ('PENDENTE','ACEITA','NAO_SELECIONADA','RETIRADA','ENCERRADA')),
  criada_em TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
  pendente_profissional BIGINT GENERATED ALWAYS AS (CASE WHEN estado='PENDENTE' THEN profissional_id ELSE NULL END),
  UNIQUE(servico_id,pendente_profissional)
);
CREATE TABLE IF NOT EXISTS contrato (
  servico_id BIGINT PRIMARY KEY REFERENCES solicitacao, proposta_id BIGINT NOT NULL UNIQUE REFERENCES proposta,
  profissional_id BIGINT NOT NULL REFERENCES usuario, valor DECIMAL(12,2) NOT NULL,
  escopo VARCHAR(2000) NOT NULL, duracao_horas DECIMAL(8,2) NOT NULL,
  contratado_em TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE IF NOT EXISTS agendamento (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, servico_id BIGINT NOT NULL REFERENCES contrato(servico_id),
  autor_id BIGINT NOT NULL REFERENCES usuario, inicio TIMESTAMP WITH TIME ZONE NOT NULL,
  fim TIMESTAMP WITH TIME ZONE NOT NULL CHECK (fim>inicio), estado VARCHAR(16) NOT NULL,
  pendente_servico BIGINT GENERATED ALWAYS AS (CASE WHEN estado='PENDENTE' THEN servico_id ELSE NULL END) UNIQUE,
  confirmado_servico BIGINT GENERATED ALWAYS AS (CASE WHEN estado='CONFIRMADO' THEN servico_id ELSE NULL END) UNIQUE
);
CREATE TABLE IF NOT EXISTS historico (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, servico_id BIGINT NOT NULL REFERENCES solicitacao,
  autor_id BIGINT REFERENCES usuario, evento VARCHAR(45) NOT NULL, origem VARCHAR(30), destino VARCHAR(30),
  detalhe VARCHAR(2000), operacao UUID NOT NULL UNIQUE, data_hora TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE IF NOT EXISTS conversa (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, servico_id BIGINT NOT NULL REFERENCES solicitacao,
  profissional_id BIGINT NOT NULL REFERENCES usuario, UNIQUE(servico_id,profissional_id)
);
CREATE TABLE IF NOT EXISTS mensagem (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, conversa_id BIGINT NOT NULL REFERENCES conversa,
  autor_id BIGINT NOT NULL REFERENCES usuario, texto VARCHAR(2000) NOT NULL,
  enviada_em TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE IF NOT EXISTS avaliacao (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, servico_id BIGINT NOT NULL REFERENCES contrato(servico_id),
  autor_id BIGINT NOT NULL REFERENCES usuario, avaliado_id BIGINT NOT NULL REFERENCES usuario,
  nota INT NOT NULL CHECK (nota BETWEEN 1 AND 5), comentario VARCHAR(500),
  criada_em TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UNIQUE(servico_id,autor_id), CHECK (autor_id<>avaliado_id)
);
CREATE VIEW IF NOT EXISTS avaliacao_publicada AS
  SELECT a.* FROM avaliacao a JOIN solicitacao s ON s.id=a.servico_id
  WHERE DATEADD('DAY',7,s.concluida_em)<=CURRENT_TIMESTAMP
     OR EXISTS (SELECT 1 FROM avaliacao b WHERE b.servico_id=a.servico_id AND b.autor_id<>a.autor_id);
CREATE TABLE IF NOT EXISTS pagamento (
  servico_id BIGINT PRIMARY KEY REFERENCES contrato(servico_id), valor DECIMAL(12,2) NOT NULL,
  estado VARCHAR(20) NOT NULL, pago_em TIMESTAMP WITH TIME ZONE
);
CREATE TABLE IF NOT EXISTS tentativa (
  referencia UUID PRIMARY KEY, servico_id BIGINT NOT NULL REFERENCES pagamento(servico_id),
  valor DECIMAL(12,2) NOT NULL, estado VARCHAR(20) NOT NULL,
  criada_em TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
  ativa_servico BIGINT GENERATED ALWAYS AS (CASE WHEN estado='EM_PROCESSAMENTO' THEN servico_id ELSE NULL END) UNIQUE
);
CREATE TABLE IF NOT EXISTS evento_provedor (
  evento_id UUID PRIMARY KEY, referencia UUID NOT NULL, servico_id BIGINT NOT NULL,
  valor DECIMAL(12,2) NOT NULL, resultado VARCHAR(16) NOT NULL
);
CREATE TABLE IF NOT EXISTS foto (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, servico_id BIGINT NOT NULL REFERENCES solicitacao,
  etapa VARCHAR(15) NOT NULL, mime VARCHAR(20) NOT NULL, conteudo BLOB NOT NULL
);
CREATE TABLE IF NOT EXISTS item_execucao (
  servico_id BIGINT REFERENCES contrato(servico_id), item INT CHECK (item BETWEEN 1 AND 5),
  PRIMARY KEY(servico_id,item)
);
CREATE INDEX IF NOT EXISTS ix_solicitacao_busca ON solicitacao(estado,categoria_id,cidade);
CREATE INDEX IF NOT EXISTS ix_historico_servico ON historico(servico_id,id);
CREATE INDEX IF NOT EXISTS ix_mensagem_conversa ON mensagem(conversa_id,id);
